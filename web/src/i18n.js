const dict = { es, en };

export function lang() {
  return S.lang || ((navigator.language || 'en').toLowerCase().startsWith('es') ? 'es' : 'en');
}

export function setLang(l) {
  S.lang = l;
  save();
  document.documentElement.lang = l;
}

/** Translates `key`; {vars} are filled in. Strings may contain <b>. */
export function t(key, vars) {
  let s = dict[lang()][key] ?? dict.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(esc(v));
  return s;
}

/** Adds strings for later phases without touching this file's tables by hand. */
export function extend(more) {
  for (const l of Object.keys(more)) Object.assign(dict[l], more[l]);
}

export const esc = (v) => String(v).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

export function fmtDay(day, opts = { day: 'numeric', month: 'short' }) {
  return new Intl.DateTimeFormat(lang(), { ...opts, timeZone: 'UTC' }).format(new Date(day + 'T12:00:00Z'));
}
